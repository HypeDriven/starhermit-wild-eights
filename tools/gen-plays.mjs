// Writes the generated play scripts in tests/native/ from the rules: the
// player's moves (first legal non-eight card by its accessible name, else an
// eight with the suit most held, else Draw) simulated with js/game.js against
// the same deterministic rivals the game runs, so every click lands.
//   node tools/gen-plays.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const W = require('../js/game.js');
const C = require('../js/content.js');
const I = require('../js/i18n.js');
I.setLocale('en-US');

/** The player's moves for a round, as play-script lines: `tap` clicks or touches cards by name; "keys" selects with →, plays with Enter, draws with D. */
export function roundLines(seed, opts, tap, choose = (plays) => plays.find((c) => c.rank !== 8) || plays[0]) {
  const st = W.newGame(seed, opts);
  const out = [];
  const runAI = () => {
    for (let g = 0; g < 400 && st.winner === null; g++) {
      if (st.pendingSuitFor === 0 || (st.pendingSuitFor === null && st.current === 0)) return;
      W.applyCommand(st, W.aiCommand(st, st.difficulty));
    }
  };
  runAI();
  for (let n = 0; n < 400 && st.winner === null; n++) {
    const la = W.legalActions(st);
    out.push('until 600 (your turn)', 'frames 10');
    const hand = st.hands[0];
    const plays = hand.filter((c) => la.plays.includes(c.id));
    const pick = plays.length ? choose(plays, st) : null;
    if (!pick) {
      out.push(tap === 'keys' ? 'key KeyD 1' : `${tap} =Draw`, 'frames 10');
      W.applyCommand(st, { type: 'draw' });
    } else {
      if (tap === 'keys') {
        const idx = hand.indexOf(pick);
        for (let k = 0; k <= idx; k++) out.push('key ArrowRight 1', 'frames 3');
        out.push('key Enter 1', 'frames 10');
      } else out.push(`${tap} =${I.cardName(pick, W.rankName)}, playable`, 'frames 10');
      W.applyCommand(st, { type: 'play', cardId: pick.id });
      if (st.pendingSuitFor === 0) {
        const counts = { hearts: 0, diamonds: 0, clubs: 0, spades: 0 };
        for (const c of st.hands[0]) counts[c.suit]++;
        const suit = W.SUITS.slice().sort((a, b) => counts[b] - counts[a])[0];
        out.push('until 300 =Declare a suit', 'frames 10', tap === 'keys' ? 'key Enter 1' : `${tap} =${I.suitName(suit)} (${counts[suit]})`, 'frames 10');
        W.applyCommand(st, { type: 'declareSuit', suit });
      }
    }
    runAI();
  }
  return { lines: out, state: st };
}
/** A seeded random chooser: the search for a winning line of play. */
function chooser(seed) {
  let a = seed >>> 0;
  const r = () => { a = (a + 0x6d2b79f5) >>> 0; let t = Math.imul(a ^ (a >>> 15), a | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
  return (plays) => { const non8 = plays.filter((c) => c.rank !== 8); const pool = non8.length ? non8 : plays; return pool[Math.floor(r() * pool.length)]; };
}
function winning(seed, opts, tap) {
  for (let k = 0; k < 500; k++) {
    const r = roundLines(seed, opts, tap, k === 0 ? undefined : chooser(k));
    if (r.state.winner === 0) return r;
  }
  throw new Error('no winning line');
}

function write(name, header, lines) {
  writeFileSync(new URL(`../tests/native/${name}`, import.meta.url), header.map((h) => (h.startsWith('#') ? h : `# ${h}`)).join('\n') + '\n' + lines.join('\n') + '\n');
}

// Journey stage 1 on a desktop window, clicked
{
  const s = C.JOURNEY[0];
  const r = winning(s.seed, { players: s.players, handSize: s.handSize, difficulty: s.difficulty }, 'click');
  const won = r.state.winner === 0;
  write('journey.play', ['Generated by tools/gen-plays.mjs: Journey stage 1 on a desktop window, every', 'card clicked in the hand tray by its accessible name, to the results.', '# viewport 1280x720@1'], [
    'until 600 Wild Eights', 'frames 60', 'click =Journey', 'until 300 stages complete', 'frames 10', 'save we-journey',
    'click 1. Stopping Train 1', 'until 600 Stage 1', 'frames 60', 'save we-stage1',
    ...r.lines, 'until 900 =Round over', 'frames 30', `expect ${won ? 'You win the round!' : 'wins the round.'}`, 'expect Score breakdown', 'save we-results',
    ...(won ? ['click =Next stage', 'until 600 Stage 2', 'frames 20', 'save we-stage2', 'key Escape 1', 'until 300 =Resume', 'frames 10', 'click =Leave round', 'until 300 =Daily Challenge'] : ['click =Menu', 'until 300 =Daily Challenge']),
  ]);
  console.log('journey.play', won ? 'won' : 'lost', r.lines.length);
}
