// Writes server.js, the platform's one server script, from tools/server-head.js,
// the shared rules (js/game.js, a UMD script: its module.exports become `W`)
// and tools/server-body.js. The platform runs server.js as one classic script
// (no imports), so the rules are inlined (after territory-trail's and
// spot-kick's tools/build-server.mjs).
//
//   node tools/build-server.mjs          rewrite server.js
//   node tools/build-server.mjs --check  exit 1 when server.js is stale
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const read = (f) => readFileSync(ROOT + f, 'utf8');
const rules = `var W = (function () {\n  var module = { exports: {} };\n${read('js/game.js').trim()}\n  return module.exports;\n})();`;
const next = [
  read('tools/server-head.js').trim(), '',
  '// RULES:BEGIN — generated by tools/build-server.mjs from js/game.js; do not edit.',
  rules,
  '// RULES:END', '',
  read('tools/server-body.js').trim(), '',
].join('\n');
const file = ROOT + 'server.js';
let cur = '';
try { cur = readFileSync(file, 'utf8'); } catch { /* new */ }
if (process.argv.includes('--check')) {
  if (next !== cur) { console.error('server.js is stale — run npm run server'); process.exit(1); }
  console.log('server.js current');
} else if (next !== cur) { writeFileSync(file, next); console.log('server.js written'); }
else console.log('server.js current');
